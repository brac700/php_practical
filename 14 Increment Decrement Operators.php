    echo("<br>"); 
    
    $x = 10;
    echo "--$x is =" . (--$x); // Outputs: 9
    echo("<br>"); 
    echo "Now x is =" . $x;   // Outputs: 9
    echo("<br>"); 
    
    $x = 10;
    echo "$x-- is =" . ($x--);// Outputs: 10
    echo("<br>"); 
    echo "Now x is =" . $x;   // Outputs: 9
